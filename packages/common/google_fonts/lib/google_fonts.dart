    return TextTheme(
      displayLarge: _buildStyle(textStyle: textTheme.displayLarge),
      displayMedium: _buildStyle(textStyle: textTheme.displayMedium),
      displaySmall: _buildStyle(textStyle: textTheme.displaySmall),
      headlineLarge: _buildStyle(textStyle: textTheme.headlineLarge),
